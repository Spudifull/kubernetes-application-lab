package main

import (
	"context"
	"encoding/json"
	"errors"
	"strings"
)

// The pause is a temporary fault on the existing Helm-owned Deployment. It
// changes only scale, preserving the image and diagnostic tracing profile.
func (e monitoringEvidence) apiAvailability(ctx context.Context, action, key string) error {
	if action == "api-alert-check" {
		return e.apiAvailabilityHTTP(ctx, key)
	}
	if action != "api-alert-stop" && action != "api-alert-start" {
		return errors.New("unsupported API availability action")
	}
	var hpa struct {
		Items []struct {
			Spec struct{ ScaleTargetRef struct{ Name, Kind string } }
		}
	}
	if err := e.lab.getJSON(ctx, &hpa, "get", "hpa", "-n", mainNS); err != nil {
		return err
	}
	for _, item := range hpa.Items {
		if item.Spec.ScaleTargetRef.Name == "lab-api" && item.Spec.ScaleTargetRef.Kind == "Deployment" {
			return errors.New("HPA controls lab-api; return to the fixed replica profile before this experiment")
		}
	}
	r, err := e.lab.kubeResult(ctx, "get", "crd", "scaledobjects.keda.sh", "--ignore-not-found=true", "-o", "name")
	if err != nil || r.code != 0 {
		return errors.New("cannot inspect KEDA ownership before API scale change")
	}
	if strings.TrimSpace(r.out) != "" {
		var list struct {
			Items []struct {
				Spec struct{ ScaleTargetRef struct{ Name string } }
			}
		}
		if err := e.lab.getJSON(ctx, &list, "get", "scaledobjects", "-n", mainNS); err != nil {
			return err
		}
		for _, item := range list.Items {
			if item.Spec.ScaleTargetRef.Name == "lab-api" {
				return errors.New("KEDA controls lab-api; restore the fixed replica profile first")
			}
		}
	}
	var deployment struct {
		Metadata struct{ Labels, Annotations map[string]string }
		Spec     struct{ Replicas int }
	}
	data, err := e.kube(ctx, "api-before", "get", "deployment/lab-api", "-n", mainNS, "-o", "json")
	if err != nil {
		return err
	}
	if err := json.Unmarshal([]byte(data), &deployment); err != nil {
		return err
	}
	if deployment.Metadata.Labels["app.kubernetes.io/instance"] != "lab-api" || deployment.Metadata.Annotations["meta.helm.sh/release-name"] != "lab-api" {
		return errors.New("expected the existing Helm-owned lab-api Deployment")
	}
	from, to := "1", "0"
	if action == "api-alert-start" {
		from, to = "0", "1"
	}
	if (action == "api-alert-stop" && deployment.Spec.Replicas != 1) || (action == "api-alert-start" && deployment.Spec.Replicas != 0) {
		return errors.New("API pause requires one fixed replica; resume requires zero replicas")
	}
	if _, err := e.kube(ctx, "api-scale", "scale", "deployment/lab-api", "-n", mainNS, "--current-replicas="+from, "--replicas="+to); err != nil {
		return err
	}
	if action == "api-alert-stop" {
		var pods podList
		if err := e.lab.getJSON(ctx, &pods, "get", "pods", "-n", mainNS, "-l", apiSelector); err != nil {
			return err
		}
		for _, p := range pods.Items {
			if _, err := e.kube(ctx, "api-stop-"+p.Metadata.Name, "wait", "--for=delete", "pod/"+p.Metadata.Name, "-n", mainNS, "--timeout=90s"); err != nil {
				return err
			}
		}
	} else {
		if _, err := e.kube(ctx, "api-rollout", "rollout", "status", "deployment/lab-api", "-n", mainNS, "--timeout=120s"); err != nil {
			return err
		}
	}
	return e.lab.event("api_availability_scale", map[string]any{"replicas": to, "scope": "temporary existing Deployment scale only; no image/profile changes"})
}

// Service proxy exercises /version without a host port-forward. An expected
// no-endpoints error is a proxy result, never a response generated by the API.
func (e monitoringEvidence) apiAvailabilityHTTP(ctx context.Context, key string) error {
	if key == "" {
		key = "healthy"
	}
	if key != "healthy" && key != "unavailable" {
		return errors.New("KEY must be healthy or unavailable")
	}
	data, err := e.kube(ctx, "api-check-deployment", "get", "deployment/lab-api", "-n", mainNS, "-o", "json")
	if err != nil {
		return err
	}
	var deployment struct {
		Spec   struct{ Replicas int }
		Status struct{ AvailableReplicas int }
	}
	if err := json.Unmarshal([]byte(data), &deployment); err != nil {
		return err
	}
	path := "/api/v1/namespaces/" + mainNS + "/services/http:lab-api:80/proxy/version"
	r, err := e.lab.kubeResult(ctx, "--request-timeout=15s", "get", "--raw", path)
	if err != nil {
		return err
	}
	b, err := json.MarshalIndent(map[string]any{"key": key, "path": path, "exit_code": r.code, "output": r.out}, "", "  ")
	if err != nil {
		return err
	}
	if err := e.save("api-service-proxy.json", b); err != nil {
		return err
	}
	if key == "unavailable" {
		if deployment.Spec.Replicas != 0 || deployment.Status.AvailableReplicas != 0 || r.code == 0 || !strings.Contains(r.out, "ServiceUnavailable") || !strings.Contains(r.out, `no endpoints available for service "lab-api"`) {
			return errors.New("expected zero API replicas and Service proxy no-endpoints rejection; inspect evidence")
		}
		return e.lab.event("api_http_availability", map[string]any{"expected": "unavailable", "transport": "Kubernetes Service proxy", "result": "no endpoints available", "scope": "proxy rejection; not an application response or host TCP test"})
	}
	var version struct{ Version, Revision string }
	if r.code != 0 || json.Unmarshal([]byte(r.out), &version) != nil || version.Version == "" || version.Revision == "" || deployment.Spec.Replicas != 1 || deployment.Status.AvailableReplicas < 1 {
		return errors.New("expected one available API replica and valid /version response; inspect evidence")
	}
	return e.lab.event("api_http_availability", map[string]any{"expected": "healthy", "transport": "Kubernetes Service proxy", "revision": version.Revision, "version": version.Version})
}
